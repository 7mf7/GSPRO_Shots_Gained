#!/usr/bin/env python3
"""
ods_upgrade.py — Versioned upgrades for the ODS report file.

The report's layout changes as the daemon gains features: columns are added,
renamed, or change units. Without an upgrade, new rows written by a newer
daemon land under an older file's headers and the columns no longer line up.

How it works
------------
* Every report carries a small "_meta" sheet recording its FORMAT version.
  Files from before versioning have no _meta and are treated as format 1.
* MIGRATIONS holds one function per step (1→2, 2→3, …). An old file is walked
  forward one step at a time, so a file several versions behind upgrades
  cleanly in a single run.
* Before anything changes, a permanent copy of the original is saved to
  backups/ocr_output.pre-upgrade-v<N>-<timestamp>.ods. Pre-upgrade copies are
  never pruned automatically.
* A file from a NEWER format than this daemon understands is left untouched.

Only the append-only data sheets (SG_Shots, SG_Holes) are migrated. Sheet1 is
the raw OCR audit trail and is never altered. Summary sheets (SG_Summary,
Round Stats, Session Log) are regenerated by the daemon on exit.

Run manually:
    python ocr_daemon.py --upgrade-ods                 # the configured report
    python ocr_daemon.py --upgrade-ods path\\to\\file.ods
"""

from __future__ import annotations

import logging
from datetime import datetime
from pathlib import Path
from typing import Callable

import storage
import strokes_gained as sg_mod

log = logging.getLogger(__name__)

FORMAT_VERSION = 6
META_SHEET = "_meta"


# ── _meta sheet ────────────────────────────────────────────────────────────────

def read_meta(data: dict) -> dict[str, str]:
    meta: dict[str, str] = {}
    for row in data.get(META_SHEET, [])[1:]:
        if len(row) >= 2 and row[0]:
            meta[row[0]] = row[1]
    return meta


def write_meta(data: dict, version: int, writer: str, **extra: str) -> None:
    meta = read_meta(data)
    meta["format_version"] = str(version)
    meta["written_by"] = writer
    meta.update({k: str(v) for k, v in extra.items()})
    data.pop(META_SHEET, None)          # re-insert so it is always the last tab
    data[META_SHEET] = [["key", "value"]] + [[k, v] for k, v in meta.items()]


def detect_format(data: dict | None) -> int:
    """
    0 — empty or new file (nothing to migrate)
    1 — written before format versioning existed
    N — the format_version recorded in _meta
    """
    if not data or not any(rows for name, rows in data.items() if name != META_SHEET):
        meta = read_meta(data or {})
        return int(meta["format_version"]) if "format_version" in meta else 0
    meta = read_meta(data)
    if "format_version" in meta:
        try:
            return int(meta["format_version"])
        except ValueError:
            return 1
    return 1


# ── Column remapping ───────────────────────────────────────────────────────────

def _remap(rows: list[list[str]], new_headers: list[str],
           aliases: dict[str, str],
           convert: Callable[[dict, dict], None] | None = None) -> tuple[list, int]:
    """
    Re-lay a sheet under *new_headers*, matching columns by header NAME.

    Matching by name rather than position is what makes this safe across any
    number of past layouts: a column that moved, was renamed (via *aliases*), or
    did not exist yet all end up in the right place, with blanks where an old
    file had no data. Returns (new_rows, data_rows_moved).
    """
    if not rows:
        return rows, 0
    old_h = [h.strip() for h in rows[0]]
    if old_h == list(new_headers):
        return rows, 0

    index: dict[str, int] = {}
    for i, h in enumerate(old_h):
        index.setdefault(aliases.get(h, h), i)

    out = [list(new_headers)]
    for r in rows[1:]:
        rec = {name: (r[i] if i < len(r) else "") for name, i in index.items()}
        legacy = {h: (r[i] if i < len(r) else "") for i, h in enumerate(old_h)}
        if convert:
            convert(rec, legacy)
        out.append([rec.get(h, "") for h in new_headers])
    return out, len(rows) - 1


# ── Migration 1 → 2 ────────────────────────────────────────────────────────────
# Brings files written before v2.8.0 in line with the v2.6+ column layout:
#  * distance columns lost their "(yd)" suffix and gained Pre/Post Unit columns,
#    with anything on the green expressed in feet;
#  * shot-geometry columns gained a Geom Unit column;
#  * Date/Time, Outcome and other columns added since are filled where known.

_SG_SHOTS_ALIASES = {
    "Pre-Dist (yd)": "Pre-Dist",   "Post-Dist (yd)": "Post-Dist",
    "Carry Game (yd)": "Carry Game", "Carry Raw (yd)": "Carry Raw",
    "Total Length (yd)": "Total Length",
    "Along Line (yd)": "Along Line", "Offline (yd)": "Offline",
    "Short/Long (yd)": "Short/Long",
    # names used by rebuild_from_log.py output
    "Pre Dist": "Pre-Dist", "Pre Lie": "Pre-Lie",
    "Post Dist": "Post-Dist", "Post Lie": "Post-Lie",
    "Category": "SG Category", "SG Cumulative": "SG Cumul.",
    "Pro Baseline": "Pro Baseline (exp.strokes)",
}


def _to_unit(value: str, lie: str) -> tuple[str, str]:
    """Convert a legacy yard value into the display unit for *lie*."""
    unit = sg_mod.display_unit(lie)
    if value in ("", None):
        return "", unit
    try:
        v = float(value)
    except ValueError:
        return value, unit
    return (f"{v * sg_mod.FT_PER_YD:.1f}" if unit == "ft" else f"{v:.1f}"), unit


def _convert_sg_shots_1_2(rec: dict, legacy: dict) -> None:
    pre_lie, post_lie = rec.get("Pre-Lie", ""), rec.get("Post-Lie", "")
    # Only columns that came from a "(yd)" header hold yards for every row and
    # need converting. Columns that already had a unit column are left alone.
    if "Pre-Dist (yd)" in legacy:
        rec["Pre-Dist"], rec["Pre Unit"] = _to_unit(legacy["Pre-Dist (yd)"], pre_lie)
    if "Post-Dist (yd)" in legacy:
        rec["Post-Dist"], rec["Post Unit"] = _to_unit(legacy["Post-Dist (yd)"], post_lie)
    for old, new in (("Carry Game (yd)", "Carry Game"), ("Carry Raw (yd)", "Carry Raw"),
                     ("Total Length (yd)", "Total Length")):
        if old in legacy:
            rec[new] = _to_unit(legacy[old], pre_lie)[0]
    geo = [("Along Line (yd)", "Along Line"), ("Offline (yd)", "Offline"),
           ("Short/Long (yd)", "Short/Long")]
    if any(old in legacy and legacy[old] for old, _ in geo):
        for old, new in geo:
            if old in legacy:
                rec[new], unit = _to_unit(legacy[old], pre_lie)
        rec["Geom Unit"] = sg_mod.display_unit(pre_lie)


def _migrate_1_to_2(data: dict, ctx: dict) -> list[str]:
    notes: list[str] = []
    headers = ctx["headers"]
    if data.get("SG_Shots"):
        data["SG_Shots"], n = _remap(data["SG_Shots"], headers["SG_Shots"],
                                     _SG_SHOTS_ALIASES, _convert_sg_shots_1_2)
        if n:
            notes.append(f"SG_Shots: {n} row(s) re-laid under the current columns; "
                         f"green distances converted to feet")
    if data.get("SG_Holes"):
        data["SG_Holes"], n = _remap(data["SG_Holes"], headers["SG_Holes"], {})
        if n:
            notes.append(f"SG_Holes: {n} row(s) re-laid under the current columns")
    return notes


# ── Migration 2 → 3 ────────────────────────────────────────────────────────────
# Format 3 stores numbers, dates and times as real typed cells instead of text.
# The values themselves do not change: storage.py types every cell by its
# content when the file is written, so this step only has to re-save. Sheet1 is
# left as text (see storage.TEXT_ONLY_SHEETS).

def _migrate_2_to_3(data: dict, ctx: dict) -> list[str]:
    n = sum(1 for name in data if name not in storage.TEXT_ONLY_SHEETS)
    return [f"{n} sheet(s) re-saved with number, date and time cells; "
            f"Sheet1 kept as text"]


# ── Migration 3 → 4 ────────────────────────────────────────────────────────────
# Adds the Club column: the club that HIT each shot. Before v3.3 every shot was
# credited to the club GSPro showed after it — the next shot's club. For old
# rows, row N−1's displayed club is exactly the club for shot N, so each shot is
# credited from its predecessor on the same hole. A hole's first shot has no
# predecessor in SG_Shots and stays blank; rebuilding from the log recovers it,
# because the log holds the hole's set-up capture.

def _migrate_3_to_4(data: dict, ctx: dict) -> list[str]:
    shots = data.get("SG_Shots")
    if not shots:
        return []
    data["SG_Shots"], _ = _remap(shots, ctx["headers"]["SG_Shots"], {})
    h = data["SG_Shots"][0]
    try:
        ih, isn, inote, iclub, ir9, idate = (h.index(c) for c in
                                            ("Hole", "Shot#", "Note", "Club", "Region9", "Date"))
    except ValueError:
        return []
    try:
        import ocr_vocab
        snap = lambda s: ocr_vocab.snap_club(s)[0] or s
    except ImportError:
        snap = lambda s: s
    def num(s):
        try:
            return int(float(s))
        except (TypeError, ValueError):
            return None
    filled = unknown = 0
    prev = None
    for row in data["SG_Shots"][1:]:
        if not row:
            continue
        row.extend([""] * (len(h) - len(row)))
        if row[inote]:                       # inferred stroke: no club, breaks the chain
            prev = None
            continue
        if not row[iclub]:
            if (prev is not None and prev[ih] == row[ih] and prev[idate] == row[idate]
                    and num(prev[isn]) is not None and num(prev[isn]) == (num(row[isn]) or 0) - 1):
                row[iclub] = snap(prev[ir9])
                filled += 1
            else:
                unknown += 1
        prev = row
    return [f"SG_Shots: Club column added — {filled} shot(s) credited to the club "
            f"shown before them; {unknown} first shot(s) of a hole left blank "
            f"(rebuild from the log to recover them)"]


# ── Migration 4 → 5 ────────────────────────────────────────────────────────────
# Two category corrections, applied to existing rows exactly as new rows get them:
#  * strokes the capture missed (inferred from the round score) move from their
#    old category — almost always Putting — to Unattributed;
#  * tee shots on par 3s move from Off Tee to Approach (PGA Tour definition).
# Session totals in round history were summed under the old rules; rebuilding
# from the log recomputes those as well.

def _migrate_4_to_5(data: dict, ctx: dict) -> list[str]:
    shots = data.get("SG_Shots")
    if not shots:
        return []
    h = shots[0]
    wind_note = []
    if "Wind Dir 1 (E1)" in h:
        # E1 reads the wind SPEED text; under the old arrow detector its values
        # were meaningless directions, so they are cleared rather than kept.
        iw = h.index("Wind Dir 1 (E1)")
        h[iw] = "Wind Speed (E1)"
        for row in shots[1:]:
            if len(row) > iw:
                row[iw] = ""
        wind_note = ["SG_Shots: 'Wind Dir 1 (E1)' renamed 'Wind Speed (E1)'; its old "
                     "values (an arrow detector reading text) cleared"]
    try:
        icat, inote, ipar, idist, iunit = (h.index(c) for c in (
            "SG Category", "Note", "Par", "Pre-Dist", "Pre Unit"))
    except ValueError:
        return []
    missed = par3 = 0
    for row in shots[1:]:
        if len(row) <= max(icat, inote, ipar, idist, iunit):
            continue
        if row[inote] in ("uncaptured stroke", "uncaptured putt") \
                and row[icat] != sg_mod.CAT_UNATTRIBUTED:
            row[icat] = sg_mod.CAT_UNATTRIBUTED
            missed += 1
        elif row[icat] == sg_mod.CAT_OTT and row[ipar].strip() == "3":
            try:
                yd = float(row[idist]) / (sg_mod.FT_PER_YD if row[iunit] == "ft" else 1.0)
            except ValueError:
                yd = 999.0
            row[icat] = sg_mod.CAT_ATG if yd <= sg_mod.ATG_THRESHOLD_YD else sg_mod.CAT_APP
            par3 += 1
    return wind_note + [f"SG_Shots: {missed} missed-capture stroke(s) moved to "
                        f"{sg_mod.CAT_UNATTRIBUTED}; {par3} par-3 tee shot(s) moved to Approach"]


def _migrate_5_to_6(data: dict, ctx: dict) -> list[str]:
    """Format 6 (v3.8.10): SG_Shots gains Speed Kept % and Spin Kept % at the end."""
    shots = data.get("SG_Shots")
    if not shots:
        return []
    data["SG_Shots"], n = _remap(shots, ctx["headers"]["SG_Shots"], {})
    return [f"SG_Shots: 'Speed Kept %' and 'Spin Kept %' added (GSPro's lie penalty); "
            f"blank for the {n} earlier shot(s)"] if n else []


MIGRATIONS: dict[int, Callable[[dict, dict], list[str]]] = {
    1: _migrate_1_to_2,
    2: _migrate_2_to_3,
    3: _migrate_3_to_4,
    4: _migrate_4_to_5,
    5: _migrate_5_to_6,
}


# ── Public entry points ────────────────────────────────────────────────────────

def upgrade_data(data: dict, ctx: dict) -> tuple[int, int, list[str]]:
    """Upgrade an in-memory report. Returns (from_version, to_version, notes)."""
    start = detect_format(data)
    if start == 0:
        write_meta(data, FORMAT_VERSION, ctx.get("writer", ""))
        return 0, FORMAT_VERSION, ["New report — format stamped"]
    if start > FORMAT_VERSION:
        return start, start, [f"File is format {start}, newer than this daemon "
                              f"understands ({FORMAT_VERSION}) — left untouched"]
    notes: list[str] = []
    v = start
    while v < FORMAT_VERSION:
        step = MIGRATIONS.get(v)
        if step is None:
            raise storage.StorageError(f"No upgrade path from format {v}")
        notes += step(data, ctx)
        v += 1
    write_meta(data, FORMAT_VERSION, ctx.get("writer", ""),
               upgraded_at=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
               upgraded_from=str(start))
    return start, v, notes


def upgrade_file(path: Path, ctx: dict) -> dict:
    """
    Upgrade a report file in place, keeping a permanent pre-upgrade copy.

    Returns a report dict: status ("current" | "upgraded" | "newer" | "missing"),
    from/to versions, notes, and the backup path when one was taken.
    """
    path = Path(path)
    data = storage.ods_read(path)
    if data is None:
        return {"status": "missing", "notes": [f"{path} does not exist"]}

    current = detect_format(data)
    if current == FORMAT_VERSION:
        return {"status": "current", "from": current, "to": current, "notes": []}
    if current > FORMAT_VERSION:
        return {"status": "newer", "from": current, "to": current,
                "notes": [f"Format {current} is newer than this daemon "
                          f"({FORMAT_VERSION}); not modified"]}

    backup = storage.snapshot(path, f"pre-upgrade-v{current}", keep=0)
    frm, to, notes = upgrade_data(data, ctx)
    storage.ods_save(path, data)
    return {"status": "upgraded", "from": frm, "to": to, "notes": notes,
            "backup": str(backup) if backup else None}
